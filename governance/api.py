"""Governance API — manages the full lifecycle of Appeal promotion/rejection,
user approval workflow, and version management.

The GovernanceAPI sits between the Appeal Trial Space (where proposed
modifications live) and the Static Archive (where approved fragments
are stored). It enforces the approval workflow, maintains the genealogical
DAG, provides rollback and version-history capabilities, and aggregates
governance statistics.
"""

